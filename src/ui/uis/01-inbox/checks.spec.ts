import { expect, test } from '@playwright/test'

test('inbox: keyboard triage, reasons, snooze, SQL rows and inbox zero', async ({ page }) => {
  await page.goto('/?ui=01&fast=1')
  await expect(page.getByTestId('ui-root')).toHaveAttribute('data-ready', 'true')
  await page.getByTestId('inbox-item-1').focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('inbox-accept-1')).toHaveText('Accepterat · Klar')
  await page.keyboard.press('j')
  await expect(page.getByTestId('inbox-expanded-2')).toBeVisible()
  await page.keyboard.press('s')
  await expect(page.getByTestId('inbox-item-2').locator('..').locator('..')).toContainText('Snoozad')
  await page.keyboard.press('r')
  await expect(page.getByTestId('inbox-save')).toBeDisabled()
  await page.getByTestId('inbox-reason').fill('Kontrollera periodvalet')
  await page.getByTestId('inbox-save').click()
  await expect(page.getByTestId('ui-memo-status')).toContainText('Returnerad')
  await page.getByTestId('inbox-item-3').click()
  await page.getByRole('button', { name: 'Fynd 3, marginWaterfall: SQL och resultatrader', exact: true }).click()
  await expect(page.getByTestId('calculation-drawer')).toContainText('Resultatrader (urval)')
  await expect(page.getByTestId('calculation-drawer')).toContainText('Ullfilt')
  await page.getByRole('button', { name: 'Stäng beräkningen' }).click()
  for (let number = 2; number <= 5; number++) { await page.getByTestId(`inbox-item-${number}`).click(); await page.getByTestId(`inbox-accept-${number}`).click() }
  await page.getByTestId('inbox-item-watch').click()
  await page.getByTestId('ui-propose-watch').click()
  await expect(page.getByTestId('ui-watch-status')).toContainText('Föreslagen')
  await page.getByTestId('ui-approve-watch').click()
  await expect(page.getByText('Inkorg noll.', { exact: false })).toBeVisible()
})

