import { expect, test } from '@playwright/test'

test('diff: reviewer ink, return reason, all-claims merge gate and named publication', async ({ page }) => {
  await page.goto('/?ui=02&fast=1')
  await expect(page.getByTestId('ui-root')).toHaveAttribute('data-ready', 'true')
  // June alone differs from the pooled April–June figure in the analyst's finding.
  await expect(page.getByTestId('diff-claim-1').locator('del').first()).toContainText('50,8')
  await expect(page.getByTestId('diff-claim-1').locator('ins').first()).toContainText('44,7')
  await page.getByTestId('diff-previous').click()
  await expect(page.getByTestId('diff-baseline')).toContainText('juni 2026')
  await page.getByTestId('diff-current').click()
  await page.getByTestId('diff-edit-1').click()
  await expect(page.getByTestId('diff-save')).toBeDisabled()
  await page.getByTestId('diff-reason').fill('Stäm av med leverantören')
  await page.getByTestId('diff-save').click()
  await page.getByTestId('diff-accept-2').click()
  await expect(page.getByTestId('ui-memo-status')).toContainText('Granskas')
  await expect(page.getByTestId('diff-note-1')).toContainText('Stäm av med leverantören')
  await page.getByTestId('diff-return-3').click()
  await page.getByTestId('diff-reason').fill('Behöver kontrollera raderna')
  await page.getByTestId('diff-save').click()
  await expect(page.getByTestId('ui-memo-status')).toContainText('Returnerad')
  await page.getByTestId('diff-reviewer').fill('Patrik')
  await expect(page.getByTestId('diff-merge')).toBeDisabled()
  for (let number = 1; number <= 5; number++) await page.getByTestId(`diff-accept-${number}`).click()
  await expect(page.getByTestId('diff-merge')).toBeDisabled()
  await page.getByTestId('ui-propose-watch').click()
  await page.getByTestId('ui-approve-watch').click()
  await page.getByTestId('diff-merge').click()
  await expect(page.getByTestId('diff-published')).toContainText('Granskad av Patrik')
  await expect(page.getByTestId('diff-note-1')).toContainText('Stäm av med leverantören')
})

