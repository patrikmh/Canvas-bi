import { expect, test } from '@playwright/test'
test('Galleri: complete economics, sorting, category filtering and cited drill-in', async ({ page }, info) => {
  await page.goto('/?ui=10&fast=1')
  await expect(page.getByTestId('ui-root')).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('.catalogue-loading')).toHaveCount(0)
  await expect(page.locator('.product-print')).toHaveCount(12)
  await expect(page.getByTestId('gallery-worst')).toContainText('Linnepläd')
  await expect(page.getByTestId('gallery-worst').locator('.price-line')).toHaveAttribute('d', /M.+L/)
  await page.getByTestId('gallery-sort').selectOption('omsättning')
  await expect(page.getByTestId('gallery-worst')).toContainText('Ullfilt')
  await page.getByTestId('gallery-filter').selectOption('Textil')
  await expect(page.locator('.product-print')).toHaveCount(6)
  await page.getByTestId('gallery-sort').selectOption('avvikelse')
  await page.getByTestId('gallery-worst').click()
  await expect(page.getByTestId('gallery-sheet')).toContainText('Linnepläd')
  await page.getByTestId('ui-citation-7').click()
  await expect(page.getByTestId('calculation-drawer')).toContainText('Resultatrader (urval)')
  await expect(page.getByTestId('calculation-drawer')).toContainText("WHERE product='Linnepläd'")
  await page.getByRole('button', { name: 'Stäng beräkningen' }).click()
  await page.getByTestId('ui-accept-3').click()
  await expect(page.getByTestId('ui-memo-status')).toContainText('Granskas')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (info.project.name === 'mobile') {
    await page.getByTestId('gallery-sheet').evaluate(element => element.scrollTo({ top: 0, behavior: 'instant' }))
    await page.screenshot({ path: 'design-shots/out/u10-mobile.png' })
  }
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('gallery-sheet')).toHaveCount(0)
})
