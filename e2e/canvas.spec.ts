import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function boot(page: Page) {
  await page.goto('/')
  await expect(page.getByTestId('app-root')).toHaveAttribute('data-ready', 'true')
}
async function saved(page: Page) {
  return page.evaluate(() => JSON.parse(localStorage.getItem('canvas-bi:v1:layout')!))
}

test('default canvas, palette add, undo, clear, reset and persisted layout', async ({ page }) => {
  await boot(page)
  await expect(page.getByTestId('card-insight')).toContainText('Marginalen är det enda som behöver din uppmärksamhet.')
  for (const metric of ['revenue', 'margin', 'orders', 'customers']) await expect(page.getByTestId(`kpi-${metric}`)).toBeVisible()
  await expect(page.getByTestId('card-waterfall')).toContainText('Vad förklarar marginalfallet')
  await expect(page.getByRole('button', { name: 'Ångra', exact: true })).toBeDisabled()
  await page.screenshot({ path: 'e2e-screens/01-dashboard.png', animations: 'disabled' })
  const before = (await saved(page)).cards.length
  await page.getByTestId('palette-text').click()
  await expect(page.getByLabel('Anteckning')).toBeVisible()
  await page.getByLabel('Anteckning').fill('Nästa ledningsmöte')
  await page.getByLabel('Anteckning').blur()
  await page.reload()
  await expect(page.getByTestId('app-root')).toHaveAttribute('data-ready', 'true')
  await expect(page.getByLabel('Anteckning')).toHaveValue('Nästa ledningsmöte')
  await page.getByRole('button', { name: 'Återställ demon' }).click()
  await page.getByTestId('palette-text').click()
  await expect.poll(async () => (await saved(page)).cards.length).toBe(before + 1)
  await page.getByRole('button', { name: 'Ångra', exact: true }).click()
  await expect(page.getByLabel('Anteckning')).toHaveCount(0)
  await page.getByRole('button', { name: 'Töm ytan' }).click()
  await expect(page.locator('[data-card-id]')).toHaveCount(0)
  await expect(page.getByText('En tom yta, nya möjligheter.')).toBeVisible()
  await page.getByRole('button', { name: 'Återställ demon' }).click()
  await expect(page.locator('[data-card-id]')).toHaveCount(before)
  await expect(page.getByTestId('kpi-revenue')).toContainText(/503\s+tkr/)
})

test('drag and resize change geometry and undo restores it', async ({ page }) => {
  await boot(page)
  const original = await saved(page)
  const card = page.getByTestId('card-kpi-revenue')
  const handle = card.locator('.drag-handle')
  await handle.scrollIntoViewIfNeeded()
  const box = (await handle.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 200, box.y + box.height / 2 + 65, { steps: 15 })
  await page.mouse.up()
  await expect.poll(async () => (await saved(page)).layout.find((item: { i: string }) => item.i === 'kpi-revenue')).not.toEqual(original.layout.find((item: { i: string }) => item.i === 'kpi-revenue'))
  await page.getByRole('button', { name: 'Ångra', exact: true }).click()
  await expect.poll(async () => (await saved(page)).layout).toEqual(original.layout)
  await card.focus()
  const resize = card.locator('.react-resizable-handle-se')
  await resize.scrollIntoViewIfNeeded()
  const corner = (await resize.boundingBox())!
  await page.mouse.move(corner.x + corner.width / 2, corner.y + corner.height / 2)
  await page.mouse.down()
  await page.mouse.move(corner.x + corner.width / 2 + 65, corner.y + corner.height / 2 + 55, { steps: 12 })
  await page.mouse.up()
  await expect.poll(async () => (await saved(page)).layout.find((item: { i: string }) => item.i === 'kpi-revenue').h).toBeGreaterThan(original.layout.find((item: { i: string }) => item.i === 'kpi-revenue').h)
  await page.getByRole('button', { name: 'Ångra', exact: true }).click()
  await expect.poll(async () => (await saved(page)).layout).toEqual(original.layout)
})

test('palette drag drop, removal, all card types and month recomputation', async ({ page }) => {
  await boot(page)
  await page.getByTestId('palette-bars').dragTo(page.getByTestId('canvas'), { targetPosition: { x: 220, y: 300 } })
  await expect(page.locator('.kind-bars')).toHaveCount(1)
  const bars = page.locator('.kind-bars')
  await bars.click({ position: { x: 100, y: 16 } })
  await bars.getByRole('button', { name: 'Ta bort Omsättning per produkt', exact: true }).click()
  await expect(page.locator('.kind-bars')).toHaveCount(0)
  await page.getByRole('button', { name: 'Ångra', exact: true }).click()
  await expect(page.locator('.kind-bars')).toHaveCount(1)
  await page.getByTestId('palette-table').click()
  await expect(page.locator('.kind-table')).toContainText('Ullfilt')
  await page.getByRole('combobox', { name: 'Period' }).selectOption('2026-06')
  await expect(page.getByTestId('app-root')).toHaveAttribute('data-ready', 'true')
  await expect(page.getByTestId('kpi-revenue')).not.toContainText(/503\s+tkr/)
  await expect(page.getByTestId('card-waterfall')).toContainText('maj–juni 2026')
  await expect(page.locator('.kind-bars')).toContainText('juni 2026')
  await page.getByRole('button', { name: 'Återställ demon' }).click()
  await expect(page.getByTestId('kpi-revenue')).toContainText(/503\s+tkr/)
})

test('waterfall and mobile screenshots; mobile has no horizontal overflow', async ({ page }) => {
  await boot(page)
  await page.getByRole('button', { name: 'Visa varför', exact: true }).click()
  await expect(page.getByTestId('card-waterfall')).toHaveClass(/selected/)
  await page.getByTestId('card-waterfall').scrollIntoViewIfNeeded()
  await expect(page.getByRole('heading', { name: 'Ledningsöversikt', exact: true })).toBeInViewport()
  await expect(page.getByRole('heading', { name: 'Canvas BI', exact: true })).toBeInViewport()
  await expect(page.getByRole('heading', { name: 'Assistent', exact: true })).toBeInViewport()
  expect(await page.evaluate('document.documentElement.scrollHeight <= window.innerHeight')).toBe(true)
  await page.waitForTimeout(400)
  await page.screenshot({ path: 'e2e-screens/02-waterfall.png', animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.mobile-cards')).toBeVisible()
  await page.getByTestId('card-insight').scrollIntoViewIfNeeded()
  await page.evaluate('window.scrollTo(0, 0)')
  await page.waitForTimeout(400)
  expect(await page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')).toBe(true)
  await page.screenshot({ path: 'e2e-screens/07-mobile.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Assistent', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Assistent' })).toBeVisible()
  await page.getByRole('button', { name: 'Stäng assistenten' }).click()
  await page.getByRole('button', { name: 'Komponenter', exact: false }).click()
  await expect(page.getByTestId('palette-text')).toBeVisible()
})
