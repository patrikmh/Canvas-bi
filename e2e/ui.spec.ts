import { test, expect } from '@playwright/test'
import { registeredUiIds, readUiManifest, runUiSteps } from '../design-shots/ui-harness.ts'

for (const id of registeredUiIds) {
  test(`UI ${id}: offline analysis and explicit watch approval`, async ({ page }) => {
    const errors: string[] = []
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`/?ui=${id}&fast=1`)
    await expect(page.getByTestId('ui-root')).toBeVisible()
    await expect(page.getByTestId('ui-root')).toHaveAttribute('data-ready', 'true')
    const manifest = await readUiManifest(page)
    expect(manifest.map(def => def.id).sort()).toEqual(registeredUiIds)
    const def = manifest.find(def => def.id === id)!
    await runUiSteps(page, def.smoke.openApproval)
    const propose = page.getByTestId('ui-propose-watch')
    if (await propose.isVisible()) await propose.click()
    await expect(page.getByTestId('ui-watch-status')).toContainText('Föreslagen')
    await page.getByTestId('ui-approve-watch').click()
    await expect(page.getByTestId('ui-watch-status')).toContainText('Aktiv')
    await expect(page.getByTestId('ui-activity-entry').filter({ hasText: 'Bevakning godkänd' })).toBeVisible()
    expect(errors).toEqual([])
  })
}

test('UI 99: citations, review reasons, sign-off, rejection and period reset', async ({ page }) => {
  const external: string[] = []
  page.on('request', request => { if (new URL(request.url()).hostname !== '127.0.0.1' && request.url().startsWith('http')) external.push(request.url()) })
  await page.goto('/?ui=99&fast=1')
  await expect(page.getByTestId('ui-root')).toHaveAttribute('data-ready', 'true')
  await expect(page.getByTestId('ui-kpis')).toContainText('503')
  await page.getByTestId('ui-citation-3').first().click()
  await expect(page.getByTestId('calculation-drawer')).toContainText('Resultatrader (urval)')
  await expect(page.getByTestId('calculation-drawer')).toContainText('Ullfilt')
  await expect(page.getByTestId('calculation-drawer')).toContainText('WITH periods AS')
  await page.getByRole('button', { name: 'Stäng beräkningen' }).click()
  await page.getByTestId('ui-accept-1').click()
  await expect(page.getByTestId('ui-memo-status')).toContainText('Granskas')
  await page.getByTestId('ui-edit-1').click()
  await page.getByTestId('ui-review-reason').fill('Förtydliga periodvalet')
  await page.getByTestId('ui-save-review').click()
  await expect(page.getByTestId('ui-review-note-1')).toContainText('Förtydliga periodvalet')
  await page.getByTestId('ui-reject-1').click()
  await expect(page.getByTestId('ui-save-review')).toBeDisabled()
  await page.getByTestId('ui-review-reason').fill('Kontrollera perioden')
  await page.getByTestId('ui-save-review').click()
  await expect(page.getByTestId('ui-memo-status')).toContainText('Returnerad')
  await page.getByTestId('ui-propose-watch').click()
  await page.getByTestId('ui-reject-watch').click()
  await expect(page.getByTestId('ui-watch-status')).toContainText('Avvisad')
  for (let number = 1; number <= 5; number++) await page.getByTestId(`ui-accept-${number}`).click()
  await expect(page.getByTestId('ui-memo-status')).toContainText('Godkänd')
  await page.getByTestId('ui-reviewer').fill('Patrik')
  await page.getByTestId('ui-signoff-submit').click()
  await expect(page.getByTestId('ui-signoff')).toContainText('Granskad av: Patrik')
  await page.getByTestId('ui-question').fill('Vad är marginalen i juli?')
  await page.getByTestId('ui-ask').click()
  await expect(page.getByTestId('ui-answer')).toContainText('juli 2026')
  await page.getByTestId('ui-period').selectOption('2026-06')
  await expect(page.getByTestId('ui-root')).toHaveAttribute('data-ready', 'true')
  await expect(page.getByTestId('ui-memo-status')).toContainText('Utkast')
  await expect(page.getByTestId('ui-signoff')).toContainText('Granskad av: —')
  await expect(page.getByTestId('ui-review-note-1')).toHaveCount(0)
  await page.getByTestId('ui-question').fill('Varför ändrades marginalen?')
  await page.getByTestId('ui-ask').click()
  await expect(page.getByTestId('ui-root')).toHaveAttribute('data-ready', 'true')
  await expect(page.getByTestId('ui-answer')).toContainText('juni 2026')
  expect(external).toEqual([])
})

test('unknown UI falls back to App and UI theme overrides survive the overview link', async ({ page }) => {
  await page.goto('/?ui=98&fast=1')
  await expect(page.getByTestId('app-root')).toBeVisible()
  await expect(page.getByTestId('ui-root')).toHaveCount(0)
  await page.goto('/?ui=99&theme=02&fast=1')
  await expect(page.getByTestId('ui-root')).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('html')).toHaveAttribute('data-theme', '02')
  await page.getByRole('link', { name: 'Till översikten' }).click()
  await expect(page.getByTestId('app-root')).toBeVisible()
  expect(new URL(page.url()).searchParams.has('ui')).toBe(false)
  await expect(page.locator('html')).toHaveAttribute('data-theme', '02')
})
