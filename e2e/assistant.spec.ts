test('settings key stays in localStorage, can be cleared, and offline remains default', async ({ page }) => {
  const requests: string[] = []
  await page.route(/https:\/\/(api\.openai\.com|api\.anthropic\.com|openrouter\.ai)\//, route => { requests.push(route.request().url()); return route.abort() })
  await page.goto('/?fast=1')
  await expect(page.getByTestId('app-root')).toHaveAttribute('data-ready', 'true')
  await page.getByRole('button', { name: 'Inställningar', exact: true }).click()
  await page.getByLabel('Leverantör').selectOption('Anthropic')
  await page.getByLabel('Modell', { exact: true }).fill('test-model')
  await page.getByLabel('API-nyckel').fill('test-only-key')
  await page.getByLabel('Använd LLM för fritext').check()
  await page.getByRole('button', { name: 'Spara', exact: true }).click()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('canvas-bi-llm') ?? '{}').key)).toBe('test-only-key')
  await page.getByRole('button', { name: 'Inställningar', exact: true }).click()
  await page.getByRole('button', { name: 'Rensa nyckeln' }).click()
  expect(await page.evaluate(() => localStorage.getItem('canvas-bi-llm'))).toBeNull()
  await expect(page.getByLabel('Använd LLM för fritext')).not.toBeChecked()
  await page.getByRole('button', { name: 'Stäng inställningar' }).click()
  await page.getByRole('textbox', { name: 'Fråga eller be mig ändra något' }).fill('compare revenue')
  await page.getByRole('button', { name: 'Skicka', exact: true }).click()
  await expect(page.getByTestId('assistant-message').last()).toContainText(/503\s+tkr/)
  expect(requests).toEqual([])
})
