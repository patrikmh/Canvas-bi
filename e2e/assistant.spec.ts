import { test, expect } from '@playwright/test'

test('offline assistant trace, explanations, card action, approval, watch and activity without LLM requests', async ({ page }) => {
  const requests: string[] = []
  await page.route(/https:\/\/(api\.openai\.com|api\.anthropic\.com|openrouter\.ai)\//, route => { requests.push(route.request().url()); return route.abort() })
  await page.goto('/?fast=1')
  await expect(page.getByTestId('app-root')).toHaveAttribute('data-ready', 'true')
  for (let index = 0; index < 5; index++) await expect(page.getByTestId(`trace-step-${index}`)).toHaveAttribute('data-status', 'done')
  await page.getByTestId('trace-step-0').locator('summary').click()
  await expect(page.getByTestId('trace-step-0')).toContainText('kpiSnapshot')
  await expect(page.getByTestId('trace-step-0')).toContainText('FROM sales')
  await page.getByTestId('trace-step-0').locator('summary').click()
  await page.screenshot({ path: 'e2e-screens/08-agent-trace.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Varför ändrades marginalen?', exact: true }).click()
  const answer = page.getByTestId('assistant-message').last()
  await expect(answer).toContainText(/51,1\s+%.*44,7\s+%.*6,4 procentenheter/)
  await expect(answer).toContainText(/95\s+%/)
  await answer.getByRole('button', { name: 'Visa förklaringen' }).click()
  await expect(page.getByTestId('card-waterfall')).toHaveClass(/selected/)
  await expect(page.getByTestId('selected-context')).toContainText('Vad förklarar marginalfallet')
  await page.getByRole('button', { name: 'Visa marginal per produkt', exact: true }).click()
  await expect(page.getByTestId('assistant-message').last()).toContainText(/Linnepläd \(−14,3\s+p\.e\.\).*Ullfilt \(−14,2\s+p\.e\.\)/)
  await expect(page.getByTestId('detail-view')).toContainText('Bruttomarginal per produkt')
  await page.getByRole('textbox', { name: 'Fråga eller be mig ändra något' }).fill('lägg till en tabell')
  await page.getByRole('button', { name: 'Skicka', exact: true }).click()
  await expect(page.locator('.kind-table')).toHaveCount(1)
  await page.getByRole('button', { name: 'Bevaka marginalen', exact: true }).last().click()
  await expect(page.getByTestId('approval-card')).toContainText('APPROVAL REQUIRED')
  await page.getByTestId('approval-card').locator('summary').click()
  await expect(page.getByTestId('approval-card')).toContainText('AUTONOMOUS')
  await expect(page.getByTestId('approval-card')).toContainText('POLICY-BOUNDED')
  await page.getByRole('button', { name: 'Fråga agenten' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'e2e-screens/09-approval.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Godkänn', exact: true }).click()
  await expect(page.getByTestId('watch-list')).toContainText('Aktiv')
  await expect(page.getByTestId('watch-alert')).toContainText(/Larm: bruttomarginalen 44,7\s+% < 46\s+%/)
  await page.screenshot({ path: 'e2e-screens/10-watch-active.png', animations: 'disabled' })
  await page.getByRole('tab', { name: 'Aktivitet', exact: true }).click()
  for (const action of ['Analys klar', 'Verktyg: unitEconomics', 'Kort tillagt', 'Tabell', 'Bevakning föreslagen', 'Bevakning godkänd', 'Simulerat larm']) await expect(page.getByTestId('activity-log')).toContainText(action)
  await page.screenshot({ path: 'e2e-screens/11-activity-log.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Inställningar', exact: true }).click()
  await expect(page.getByTestId('settings-llm')).toContainText('Nyckeln lagras bara i din webbläsare')
  await expect(page.getByLabel('Använd LLM för fritext')).not.toBeChecked()
  await page.screenshot({ path: 'e2e-screens/12-settings-llm.png', animations: 'disabled' })
  expect(requests).toEqual([])
})

